// Bundles src/*.js (in filename order) + game-config.json into the HTML template -> index.html (double-click to play).
// Also keeps the two generated, offline-ready support files up to date:
//   vendor/three/three.bundle.js   the 3D engine as one classic script (tools/bundle-three.mjs)  - no CDN needed
//   assets/textures.pack.js        assets/textures/* packed for file:// pages                     - no painting at start-up
//   assets/terrain.pack.js         assets/terrain/*  (baked heightfield) packed the same way          - no terrain generation at start-up
//   node build.mjs           build
//   node build.mjs --check   build, then syntax-check the generated module with `node --check`
import { readFileSync, writeFileSync, readdirSync, mkdtempSync, rmSync, existsSync, statSync, mkdirSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { tmpdir } from 'node:os';
import { fileURLToPath } from 'node:url';
import { spawnSync } from 'node:child_process';
import { createHash } from 'node:crypto';
import { ensureThreeBundle } from './tools/bundle-three.mjs';

const root = dirname(fileURLToPath(import.meta.url));
// hash of the code that generates the terrain: a baked heightfield pack is only used while this still matches (see src/10-terrain.js)
const TERRAIN_SRC_HASH = createHash('sha1').update(readFileSync(join(root, 'src', '00-core.js'))).update(readFileSync(join(root, 'src', '10-terrain.js'))).digest('hex').slice(0, 16);

/* ---- engine bundle */
const eng = ensureThreeBundle(join(root, 'vendor'));
console.log(eng.rebuilt ? `bundled three.js r169 (${eng.modules} modules) -> vendor/three/three.bundle.js, ${(eng.bytes / 1024).toFixed(0)} KB` : `vendor/three/three.bundle.js up to date (${(eng.bytes / 1024).toFixed(0)} KB)`);

/* ---- texture pack: assets/textures/manifest.json + image files -> one script that defines window.__HR_TEXPACK */
{
  const dir = join(root, 'assets', 'textures'), man = join(dir, 'manifest.json'), out = join(root, 'assets', 'textures.pack.js');
  const MIME = { png: 'image/png', webp: 'image/webp', jpg: 'image/jpeg' };
  if (!existsSync(man)) {
    mkdirSync(join(root, 'assets'), { recursive: true });
    writeFileSync(out, '/* no baked textures yet: run `node tools/bake-textures.mjs` then `node build.mjs`; the game paints them itself meanwhile */\nwindow.__HR_TEXPACK = null;\n');
    console.log('no assets/textures/manifest.json: texture pack left empty (the game paints textures at start-up)');
  } else {
    const manifest = JSON.parse(readFileSync(man, 'utf8'));
    const newest = Math.max(statSync(man).mtimeMs, ...Object.values(manifest).map((e) => statSync(join(dir, e.file)).mtimeMs));
    if (existsSync(out) && statSync(out).mtimeMs > newest) console.log(`assets/textures.pack.js up to date (${(statSync(out).size / 1048576).toFixed(2)} MB)`);
    else {
      let js = '/* GENERATED by build.mjs from assets/textures/ - do not edit. Image files cannot be handed to WebGL from a double-clicked (file://) page, so they ship as data URLs in a script. */\nwindow.__HR_TEXPACK = {\n';
      for (const [name, e] of Object.entries(manifest)) {
        const data = readFileSync(join(dir, e.file)).toString('base64');
        js += ` ${JSON.stringify(name)}: ${JSON.stringify({ u: `data:${MIME[e.file.split('.').pop()]};base64,${data}`, w: e.w, h: e.h, srgb: e.srgb, repeat: e.repeat, mip: e.mip, aniso: e.aniso })},\n`;
      }
      js += '};\n';
      writeFileSync(out, js);
      console.log(`packed ${Object.keys(manifest).length} textures -> assets/textures.pack.js, ${(js.length / 1048576).toFixed(2)} MB`);
    }
  }
}

/* ---- terrain pack: assets/terrain/{heightfield.bin,meta.json} -> one script that defines window.__HR_TERRAINPACK (only if baked from the current source) */
{
  const dir = join(root, 'assets', 'terrain'), bin = join(dir, 'heightfield.bin'), meta = join(dir, 'meta.json'), out = join(root, 'assets', 'terrain.pack.js');
  const stub = (why) => { mkdirSync(join(root, 'assets'), { recursive: true }); writeFileSync(out, '/* ' + why + ' */\nwindow.__HR_TERRAINPACK = null;\n'); console.log('terrain pack left empty: ' + why); };
  if (!existsSync(bin) || !existsSync(meta)) stub('no assets/terrain/ yet - run node tools/bake-terrain.mjs; the game generates the terrain itself meanwhile');
  else {
    const m = JSON.parse(readFileSync(meta, 'utf8'));
    if (m.hash !== TERRAIN_SRC_HASH) stub('assets/terrain was baked from older terrain code (hash ' + m.hash + ' != ' + TERRAIN_SRC_HASH + ') - run node tools/bake-terrain.mjs again');
    else if (existsSync(out) && statSync(out).mtimeMs > Math.max(statSync(bin).mtimeMs, statSync(meta).mtimeMs) && readFileSync(out, 'utf8').includes('__HR_TERRAINPACK = {"hash":"' + TERRAIN_SRC_HASH + '"')) console.log(`assets/terrain.pack.js up to date (${(statSync(out).size / 1048576).toFixed(2)} MB)`);
    else {
      const all = readFileSync(bin), nn = m.n * m.n, sizes = [nn * 4, nn * 4, nn * 4, nn * 4];       // height f32, splat u8x4, roadD f32, trenchD f32
      if (all.length !== sizes.reduce((a, c) => a + c, 0)) throw new Error('assets/terrain/heightfield.bin has the wrong size - bake again');
      let o = 0; const part = (len) => { const b = all.subarray(o, o + len).toString('base64'); o += len; return b; };
      const js = '/* GENERATED by build.mjs from assets/terrain/ - do not edit. */\nwindow.__HR_TERRAINPACK = ' + JSON.stringify({ hash: m.hash, n: m.n, h: part(sizes[0]), s: part(sizes[1]), r: part(sizes[2]), t: part(sizes[3]) }) + ';\n';
      writeFileSync(out, js);
      console.log(`packed terrain -> assets/terrain.pack.js, ${(js.length / 1048576).toFixed(2)} MB`);
    }
  }
}

/* ---- game */
const files = readdirSync(join(root, 'src')).filter((f) => f.endsWith('.js')).sort();
const config = JSON.parse(readFileSync(join(root, 'game-config.json'), 'utf8'));
// the shared balance file is injected as a constant: prices, rewards and weapon numbers come from one place (the server reads the same file)
const head = '/* ##### game-config.json (injected) ##### */\nconst CONFIG = ' + JSON.stringify(config) + ';\nconst TERRAIN_SRC_HASH = ' + JSON.stringify(TERRAIN_SRC_HASH) + ';\n';
const code = head + files.map((f) => `\n/* ##### ${f} ##### */\n` + readFileSync(join(root, 'src', f), 'utf8')).join('\n');
const html = readFileSync(join(root, 'template.html'), 'utf8').replace('{{SCRIPT}}', () => code);
writeFileSync(join(root, 'index.html'), html);
console.log('built index.html from', files.length, 'source files +', 'game-config.json,', (html.length / 1024).toFixed(0), 'KB');

if (process.argv.includes('--check')) {
  const m = html.match(/<script type="module">([\s\S]*)<\/script>\s*<\/body>/);
  const dir = mkdtempSync(join(tmpdir(), 'hr-check-')), file = join(dir, 'bundle.mjs');
  writeFileSync(file, m[1]);
  const r = spawnSync(process.execPath, ['--check', file], { encoding: 'utf8' });
  rmSync(dir, { recursive: true, force: true });
  if (r.status !== 0) { console.error('SYNTAX ERROR in the bundle:\n' + r.stderr); process.exit(1); }
  console.log('syntax check OK');
}
