// Turns the vendored three.js r169 ES modules (vendor/three) into ONE classic script, vendor/three/three.bundle.js.
//
// Why: a page opened by double-click (file://) is not allowed to `import` other files (browsers block module loads
// from file://), which is why the game used to pull three.js from a CDN. A classic <script src> *is* allowed from
// file://, so the engine now ships next to the game and needs no internet connection at all.
//
// No bundler dependency: the modules use a tiny, regular subset of ESM (named imports, `export { ... }` lists and a few
// `export function`), so a small transform is enough. Each module becomes a function scope that returns its exports.
//   import { a, b as c } from 'three';   ->  const { a, b: c } = __m.three;
//   export { X, Y as Z };                ->  (collected)  return { X, Z: Y };
import { readFileSync, writeFileSync, statSync, existsSync } from 'node:fs';
import { join, dirname, resolve, relative } from 'node:path';

/** the modules the game imports (entry points) - everything they pull in is bundled too */
export const THREE_ENTRIES = [
  'examples/jsm/postprocessing/EffectComposer.js', 'examples/jsm/postprocessing/RenderPass.js', 'examples/jsm/postprocessing/UnrealBloomPass.js',
  'examples/jsm/postprocessing/ShaderPass.js', 'examples/jsm/postprocessing/OutputPass.js', 'examples/jsm/shaders/FXAAShader.js',
  'examples/jsm/geometries/RoundedBoxGeometry.js', 'examples/jsm/environments/RoomEnvironment.js', 'examples/jsm/utils/BufferGeometryUtils.js',
];

export function bundleThree(vendorDir) {
  const root = join(vendorDir, 'three');
  const mods = new Map();           // id -> { id, code, imports:[{names,from}], exports:[[local, exported]] }
  const order = [];

  const parseNames = (list) => list.split(',').map((s) => s.trim()).filter(Boolean).map((s) => { const m = /^(\S+)\s+as\s+(\S+)$/.exec(s); return m ? [m[1], m[2]] : [s, s]; });

  function load(id, file) {
    if (mods.has(id)) return;
    let code = readFileSync(file, 'utf8');
    const imports = [], exports = [];
    // imports: `import { a, b as c } from 'x';` (possibly multi-line)
    code = code.replace(/^import\s*\{([\s\S]*?)\}\s*from\s*['"]([^'"]+)['"];?[ \t]*$/gm, (_, names, from) => { imports.push({ names: parseNames(names), from }); return ''; });
    if (/^import\s/m.test(code)) throw new Error(`bundle-three: unsupported import form in ${id}`);
    // export lists: `export { A, B as C };`
    code = code.replace(/^export\s*\{([\s\S]*?)\};?[ \t]*$/gm, (_, names) => { exports.push(...parseNames(names)); return ''; });
    // `export function f` / `export class C` / `export const x` -> plain declaration + export entry
    code = code.replace(/^export\s+(async\s+function|function\*?|class|const|let|var)\s+([A-Za-z0-9_$]+)/gm, (_, kw, name) => { exports.push([name, name]); return `${kw} ${name}`; });
    if (/^export\s/m.test(code)) throw new Error(`bundle-three: unsupported export form in ${id}`);
    mods.set(id, { id, code, imports, exports });
    for (const imp of imports) {
      if (imp.from === 'three') { imp.id = 'three'; load('three', join(root, 'three.module.js')); }
      else { const target = resolve(dirname(file), imp.from); imp.id = relative(root, target).replace(/\\/g, '/'); load(imp.id, target); }
    }
    order.push(id);       // post-order: dependencies first
  }

  load('three', join(root, 'three.module.js'));
  for (const e of THREE_ENTRIES) load(e, join(root, e));

  const safe = (id) => JSON.stringify(id);
  let out = `/* Hollow Ridge - three.js r169 (MIT, see LICENSE) bundled as one classic script by tools/bundle-three.mjs. DO NOT EDIT - regenerated by build.mjs */\n`;
  out += `(function () {\n'use strict';\nconst __m = Object.create(null);\n`;
  for (const id of order) {
    const m = mods.get(id);
    out += `\n/* ===== ${id} ===== */\n__m[${safe(id)}] = (function () {\n`;
    for (const imp of m.imports) out += `const { ${imp.names.map(([a, b]) => (a === b ? a : `${a}: ${b}`)).join(', ')} } = __m[${safe(imp.id)}];\n`;
    out += m.code + `\nreturn { ${m.exports.map(([local, exp]) => (local === exp ? local : `${JSON.stringify(exp)}: ${local}`)).join(', ')} };\n})();\n`;
  }
  // what the game reads: window.__HR3.THREE, window.__HR3.EffectComposer, ...
  const entryNames = THREE_ENTRIES.flatMap((e) => mods.get(e).exports.map(([, exp]) => `${exp}: __m[${safe(e)}][${JSON.stringify(exp)}]`));
  out += `\nwindow.__HR3 = { THREE: __m['three'], ${entryNames.join(', ')} };\n})();\n`;
  return { code: out, names: THREE_ENTRIES.flatMap((e) => mods.get(e).exports.map(([, exp]) => exp)), modules: order.length };
}

/** rewrite vendor/three/three.bundle.js only when a source file is newer (or it is missing); returns info for the build log */
export function ensureThreeBundle(vendorDir) {
  const target = join(vendorDir, 'three', 'three.bundle.js');
  const t = existsSync(target) ? statSync(target).mtimeMs : 0;
  const srcNewest = Math.max(statSync(join(vendorDir, 'three', 'three.module.js')).mtimeMs, statSync(new URL(import.meta.url)).mtimeMs, ...THREE_ENTRIES.map((e) => statSync(join(vendorDir, 'three', e)).mtimeMs));
  if (t > srcNewest) return { rebuilt: false, bytes: statSync(target).size, names: null };
  const { code, names, modules } = bundleThree(vendorDir);
  writeFileSync(target, code);
  return { rebuilt: true, bytes: code.length, names, modules };
}
